-- MrSa Properties: privacy-friendly website visitor analytics + campaign and WhatsApp click tracking
-- Run this complete script in Supabase Dashboard > SQL Editor after deploying the frontend changes.
-- Safe to re-run: creates missing objects and replaces the admin stats function.

create table if not exists public.website_page_views (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  session_id uuid not null,
  path text not null check (char_length(path) between 1 and 300),
  referrer_host text check (referrer_host is null or char_length(referrer_host) <= 180),
  traffic_source text not null default 'Direct',
  device_type text not null check (device_type in ('Mobile','Desktop','Tablet')),
  utm_source text,
  utm_medium text,
  utm_campaign text,
  viewed_at timestamptz not null default now()
);

alter table public.website_page_views add column if not exists utm_source text;
alter table public.website_page_views add column if not exists utm_medium text;
alter table public.website_page_views add column if not exists utm_campaign text;
alter table public.website_page_views drop constraint if exists website_page_views_traffic_source_check;
alter table public.website_page_views add constraint website_page_views_traffic_source_check
  check (traffic_source in ('Direct','Search','Social','Referral','WhatsApp','Facebook','Instagram','YouTube','LinkedIn'));

create index if not exists website_page_views_viewed_at_idx on public.website_page_views (viewed_at desc);
create index if not exists website_page_views_visitor_id_idx on public.website_page_views (visitor_id);
create index if not exists website_page_views_path_idx on public.website_page_views (path);
create index if not exists website_page_views_source_idx on public.website_page_views (traffic_source);

alter table public.website_page_views enable row level security;
drop policy if exists "public can record website page views" on public.website_page_views;
create policy "public can record website page views"
  on public.website_page_views for insert to anon, authenticated
  with check (visitor_id is not null and session_id is not null);
drop policy if exists "admins can read website page views" on public.website_page_views;
create policy "admins can read website page views"
  on public.website_page_views for select to authenticated
  using (public.is_admin());
grant insert on public.website_page_views to anon, authenticated;
grant select on public.website_page_views to authenticated;
grant usage, select on sequence public.website_page_views_id_seq to anon, authenticated;

create table if not exists public.website_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  session_id uuid not null,
  event_type text not null check (event_type in ('whatsapp_click')),
  path text not null check (char_length(path) between 1 and 300),
  target text check (target is null or char_length(target) <= 120),
  traffic_source text not null default 'Direct',
  utm_source text,
  utm_medium text,
  utm_campaign text,
  created_at timestamptz not null default now()
);
alter table public.website_events add column if not exists utm_source text;
alter table public.website_events add column if not exists utm_medium text;
alter table public.website_events add column if not exists utm_campaign text;
create index if not exists website_events_created_at_idx on public.website_events (created_at desc);
create index if not exists website_events_type_idx on public.website_events (event_type, created_at desc);
alter table public.website_events enable row level security;
drop policy if exists "public can record website events" on public.website_events;
create policy "public can record website events"
  on public.website_events for insert to anon, authenticated
  with check (visitor_id is not null and session_id is not null);
drop policy if exists "admins can read website events" on public.website_events;
create policy "admins can read website events"
  on public.website_events for select to authenticated
  using (public.is_admin());
grant insert on public.website_events to anon, authenticated;
grant select on public.website_events to authenticated;
grant usage, select on sequence public.website_events_id_seq to anon, authenticated;

create or replace function public.get_admin_website_visitor_stats(
  p_from timestamptz default null,
  p_to timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  result jsonb;
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  with filtered as (
    select * from public.website_page_views
    where (p_from is null or viewed_at >= p_from)
      and (p_to is null or viewed_at <= p_to)
  ), filtered_events as (
    select * from public.website_events
    where event_type = 'whatsapp_click'
      and (p_from is null or created_at >= p_from)
      and (p_to is null or created_at <= p_to)
  ), daily as (
    select date_trunc('day', viewed_at)::date as day, count(*) as views,
           count(distinct visitor_id) as visitors
    from filtered group by 1 order by 1
  ), pages as (
    select path, count(*) as views from filtered group by path order by views desc, path limit 10
  ), sources as (
    select traffic_source as label, count(*) as views from filtered group by traffic_source order by views desc
  ), devices as (
    select device_type as label, count(*) as views from filtered group by device_type order by views desc
  ), campaigns as (
    select coalesce(nullif(utm_campaign,''), nullif(utm_source,''), 'Unlabelled campaign') as label,
           count(*) as views
    from filtered where coalesce(utm_campaign,utm_source) is not null
    group by 1 order by views desc limit 10
  )
  select jsonb_build_object(
    'summary', jsonb_build_object(
      'period_visitors', (select count(distinct visitor_id) from filtered),
      'period_page_views', (select count(*) from filtered),
      'period_whatsapp_clicks', (select count(*) from filtered_events),
      'total_visitors', (select count(distinct visitor_id) from public.website_page_views),
      'total_page_views', (select count(*) from public.website_page_views),
      'total_whatsapp_clicks', (select count(*) from public.website_events where event_type = 'whatsapp_click'),
      'today_visitors', (select count(distinct visitor_id) from public.website_page_views where viewed_at >= date_trunc('day', now())),
      'today_page_views', (select count(*) from public.website_page_views where viewed_at >= date_trunc('day', now()))
    ),
    'daily', coalesce((select jsonb_agg(jsonb_build_object('day', day, 'views', views, 'visitors', visitors) order by day) from daily), '[]'::jsonb),
    'top_pages', coalesce((select jsonb_agg(jsonb_build_object('path', path, 'views', views) order by views desc) from pages), '[]'::jsonb),
    'sources', coalesce((select jsonb_agg(jsonb_build_object('label', label, 'views', views) order by views desc) from sources), '[]'::jsonb),
    'devices', coalesce((select jsonb_agg(jsonb_build_object('label', label, 'views', views) order by views desc) from devices), '[]'::jsonb),
    'campaigns', coalesce((select jsonb_agg(jsonb_build_object('label', label, 'views', views) order by views desc) from campaigns), '[]'::jsonb)
  ) into result;
  return result;
end;
$$;

revoke all on function public.get_admin_website_visitor_stats(timestamptz, timestamptz) from public;
grant execute on function public.get_admin_website_visitor_stats(timestamptz, timestamptz) to authenticated;
